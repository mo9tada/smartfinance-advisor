-- Migration script for Sprint 2: User Authentication and Management

-- Create custom types for roles and status if they don't exist
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'user_role') THEN
        CREATE TYPE user_role AS ENUM ('viewer', 'analyst', 'administrator');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'user_status') THEN
        CREATE TYPE user_status AS ENUM ('pending', 'active', 'deleted');
    END IF;
END $$;

-- Create users table
CREATE TABLE IF NOT EXISTS users (
  id              SERIAL PRIMARY KEY,
  first_name      VARCHAR(100) NOT NULL,
  last_name       VARCHAR(100) NOT NULL,
  email           VARCHAR(150) UNIQUE NOT NULL,
  phone           VARCHAR(20),
  role            user_role NOT NULL DEFAULT 'viewer',
  matricule       VARCHAR(50) UNIQUE,            -- generated by admin on approval
  password_hash   VARCHAR(255),                  -- bcrypt hash
  status          user_status DEFAULT 'pending',
  reset_code      VARCHAR(6),                    -- 6-digit OTP
  reset_code_expires_at TIMESTAMP,
  created_at      TIMESTAMP DEFAULT NOW(),
  last_login      TIMESTAMP
);

-- Index for faster lookups
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_matricule ON users(matricule);
